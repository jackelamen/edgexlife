export default function Icon({ name, size = 19, fill = false, className = '', style }) {
  const Glyph = MAP[name]
  if (import.meta.env.DEV && !Glyph) console.warn(`[Icon] no Phosphor mapping for "${name}"`)
  const Cmp = Glyph || Circle
  return (
    <span
      className={`icon${fill ? ' fill' : ''}${className ? ' ' + className : ''}`}
      style={{ fontSize: size, ...style }}
      aria-hidden="true"
    >
      <Cmp size="1em" weight={fill ? 'fill' : 'regular'} />
    </span>
  )
}
