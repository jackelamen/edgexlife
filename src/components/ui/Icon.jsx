/**
 * Phosphor icons behind the same `name` API the app has always used.
 *
 * Call sites and the `icon:` fields in lib/*.js still pass Material Symbols
 * names (`monitor_heart`, `self_improvement`, ...). Rather than touch ~250
 * call sites and every data file, this maps each of those names to its
 * Phosphor equivalent in one place. To change an icon, change its entry in
 * MAP below.
 *
 * `fill` swaps the weight to Phosphor's filled variant, which is how active
 * nav items are marked.
 *
 * The glyph is sized in `em` inside a span that carries the `icon` class, so
 * the many CSS rules that size icons via `font-size` (e.g. `.nav-item .icon`)
 * keep working unchanged.
 */
